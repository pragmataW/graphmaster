func TestUserEditBetweenInstallsDisablesRestore(t *testing.T) {
	home := fixture(t)
	e := newTestEngine(home)
	if _, err := e.Install(Options{}, claudePlan(home, "/bin/a")); err != nil {
		t.Fatal(err)
	}
	settings := filepath.Join(home, ".claude", "settings.json")
	edited := strings.Replace(read(t, settings), "\"Bash(git status)\"", "\"Bash(git status)\", \"Bash(ls)\"", 1)
	write(t, settings, edited)
	// A new binary path forces a write on top of the user's edit.
	if _, err := e.Install(Options{}, claudePlan(home, "/bin/b")); err != nil {
		t.Fatal(err)
	}
	s, _ := e.State()
	if s.Files[settings].Restorable {
		t.Fatal("record should no longer be restorable")
	}
	rep, err := e.Uninstall(Options{}, "claude")
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range rep.Files {
		if f.Path == settings && f.Action != ActionSurgical {
			t.Fatalf("action %s", f.Action)
		}
	}
	want := strings.Replace(seedClaudeSettings, "\"Bash(git status)\"", "\"Bash(git status)\", \"Bash(ls)\"", 1)
	if got := read(t, settings); got != want {
		t.Fatalf("settings:\n%s", unifiedDiff("/s", []byte(want), []byte(got)))
	}
}

