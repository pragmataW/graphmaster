// snapshot captures every file under home except graphmaster's own state
// directory; directories are recorded too so leftovers are detected.
func snapshot(t *testing.T, home string) map[string]string {
	t.Helper()
	out := map[string]string{}
	skip := filepath.Join(home, ".config", "graphmaster")
	err := filepath.WalkDir(home, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if p == skip {
			return filepath.SkipDir
		}
		rel, _ := filepath.Rel(home, p)
		if rel == ".config" {
			return nil // parent of graphmaster's own state directory
		}
		if d.IsDir() {
			out[rel+"/"] = ""
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		out[rel] = string(b)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func diffSnapshots(t *testing.T, want, got map[string]string) {
	t.Helper()
	for k, v := range want {
		if g, ok := got[k]; !ok {
			t.Errorf("missing %s", k)
		} else if g != v {
			t.Errorf("%s differs:\n%s", k, unifiedDiff("/"+k, []byte(v), []byte(g)))
		}
	}
	for k := range got {
		if _, ok := want[k]; !ok {
			t.Errorf("unexpected %s", k)
		}
	}
}

func TestInstallWritesExpectedEdits(t *testing.T) {
	home := fixture(t)
	e := newTestEngine(home)
	rep, err := e.Install(Options{}, allPlans(home, "/opt/homebrew/bin/graphmaster")...)
	if err != nil {
		t.Fatal(err)
	}
	if !rep.Changed() {
		t.Fatal("first install reported no change")
	}
	cj := read(t, filepath.Join(home, ".claude.json"))
	for _, s := range []string{"// a comment that must survive", `"github": {`, `"graphmaster": {`, `"command": "/opt/homebrew/bin/graphmaster"`} {
		if !strings.Contains(cj, s) {
			t.Errorf(".claude.json lacks %q:\n%s", s, cj)
		}
	}
	st := read(t, filepath.Join(home, ".claude", "settings.json"))
	if !strings.Contains(st, "~/bin/guard.sh") || !strings.Contains(st, "pre-tool-use") || !strings.Contains(st, `"SessionStart": [`) {
		t.Errorf("settings.json:\n%s", st)
	}
	toml := read(t, filepath.Join(home, ".codex", "config.toml"))
	if !strings.HasPrefix(toml, seedCodexTOML) || !strings.Contains(toml, "# graphmaster:begin v1\n[mcp_servers.graphmaster]") {
		t.Errorf("config.toml:\n%s", toml)
	}
	if got := read(t, filepath.Join(home, ".codex", "AGENTS.md")); got != "<!-- graphmaster:begin v1 -->\nUse graphmaster.\n<!-- graphmaster:end -->\n" {
		t.Errorf("AGENTS.md = %q", got)
	}
	if _, err := os.Stat(filepath.Join(home, ".config", "opencode", "plugins", "graphmaster.js")); err != nil {
		t.Error(err)
	}

	// Manifest records hashes and exact insertions.
	s, err := e.State()
	if err != nil {
		t.Fatal(err)
	}
	rec := s.Files[filepath.Join(home, ".claude", "settings.json")]
	if rec == nil || !rec.Existed || rec.PreHash != hashBytes([]byte(seedClaudeSettings)) || !rec.Restorable {
		t.Fatalf("settings record = %+v", rec)
	}
	if rec.PostHash != hashBytes([]byte(st)) || len(rec.Insertions) != 2 || rec.Insertions[0].Kind != KindJSONElement {
		t.Fatalf("settings record = %+v", rec)
	}
	if len(rec.Created) != 1 || rec.Created[0].Pointer != "/hooks/SessionStart" {
		t.Fatalf("created = %+v", rec.Created)
	}
	if read(t, rec.Backup) != seedClaudeSettings {
		t.Fatal("backup content mismatch")
	}
	if fi, _ := os.Stat(rec.Backup); fi.Mode().Perm() != 0o600 {
		t.Fatalf("backup perm %v", fi.Mode().Perm())
	}
	if !strings.HasPrefix(rec.Backup, filepath.Join(home, ".config", "graphmaster", "backups", "20261011T120000")) {
		t.Fatalf("backup path %s", rec.Backup)
	}
	agents := filepath.Join(home, ".codex", "AGENTS.md")
	if r := s.Files[agents]; r == nil || r.Existed || r.Backup != "" || r.Insertions[0].Marker != "" || r.Insertions[0].Kind != KindMarker {
		t.Fatalf("AGENTS.md record = %+v", r)
	}
	if got := s.Agents(); strings.Join(got, ",") != "claude,codex,opencode" {
		t.Fatalf("agents = %v", got)
	}
}

func TestInstallTwiceIsIdempotent(t *testing.T) {
	home := fixture(t)
	e := newTestEngine(home)
	plans := allPlans(home, "/usr/local/bin/graphmaster")
	if _, err := e.Install(Options{}, plans...); err != nil {
		t.Fatal(err)
	}
	snap := snapshot(t, home)
	statePath, _ := e.env.StatePath()
	state1 := read(t, statePath)

	rep, err := e.Install(Options{}, plans...)
	if err != nil {
		t.Fatal(err)
	}
	if rep.Changed() {
		t.Fatalf("second install changed files:\n%s", rep)
	}
	diffSnapshots(t, snap, snapshot(t, home))
	if read(t, statePath) != state1 {
		t.Fatal("state changed on idempotent install")
	}
}

func TestUninstallRestoresByteExact(t *testing.T) {
	home := fixture(t)
	before := snapshot(t, home)
	e := newTestEngine(home)
	plans := allPlans(home, "/usr/local/bin/graphmaster")
	if _, err := e.Install(Options{}, plans...); err != nil {
		t.Fatal(err)
	}
	// Re-install with a moved binary: still restorable byte-exact.
	if _, err := e.Install(Options{}, allPlans(home, "/opt/homebrew/bin/graphmaster")...); err != nil {
		t.Fatal(err)
	}
	st := read(t, filepath.Join(home, ".claude", "settings.json"))
	if strings.Contains(st, "/usr/local/bin") || strings.Count(st, "pre-tool-use") != 1 {
		t.Fatalf("stale hook not replaced:\n%s", st)
	}
	rep, err := e.Uninstall(Options{})
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range rep.Files {
		if f.Action != ActionRestore && f.Action != ActionDelete {
			t.Errorf("%s: action %s, want restore/delete", f.Path, f.Action)
		}
	}
	diffSnapshots(t, before, snapshot(t, home))
	s, _ := e.State()
	if len(s.Files) != 0 {
		t.Fatalf("state not emptied: %+v", s.Files)
	}
}

func TestUninstallAfterUserEditIsSurgical(t *testing.T) {
	home := fixture(t)
	e := newTestEngine(home)
	if _, err := e.Install(Options{}, allPlans(home, "/usr/local/bin/graphmaster")...); err != nil {
		t.Fatal(err)
	}
	settings := filepath.Join(home, ".claude", "settings.json")
	claudeMD := filepath.Join(home, ".claude", "CLAUDE.md")
	codex := filepath.Join(home, ".codex", "config.toml")
	plugin := filepath.Join(home, ".config", "opencode", "plugins", "graphmaster.js")

	userEdit := func(s string) string {
		return strings.Replace(s, "{\n", "{\n  \"model\": \"opus\", // user added\n", 1)
	}
	write(t, settings, userEdit(read(t, settings)))
	write(t, claudeMD, read(t, claudeMD)+"\n- User rule added later.\n")
	write(t, codex, read(t, codex)+"\n[mcp_servers.later]\ncommand = \"later\"\n")
	write(t, plugin, read(t, plugin)+"// user tweak\n")

	rep, err := e.Uninstall(Options{}, "claude", "codex", "opencode")
	if err != nil {
		t.Fatal(err)
	}
	actions := map[string]Action{}
	for _, f := range rep.Files {
		actions[f.Path] = f.Action
	}
	if actions[settings] != ActionSurgical || actions[filepath.Join(home, ".claude.json")] != ActionRestore {
		t.Fatalf("actions = %v", actions)
	}
	if got, want := read(t, settings), userEdit(seedClaudeSettings); got != want {
		t.Errorf("settings.json:\n%s", unifiedDiff("/settings.json", []byte(want), []byte(got)))
	}
	if got, want := read(t, claudeMD), seedClaudeMD+"\n- User rule added later.\n"; got != want {
		t.Errorf("CLAUDE.md = %q, want %q", got, want)
	}
	if got, want := read(t, codex), seedCodexTOML+"\n[mcp_servers.later]\ncommand = \"later\"\n"; got != want {
		t.Errorf("config.toml = %q, want %q", got, want)
	}
	if _, err := os.Stat(plugin); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("generated plugin should be removed: %v", err)
	}
	if _, err := os.Stat(filepath.Join(home, ".config", "opencode")); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("created dirs should be removed: %v", err)
	}
}

