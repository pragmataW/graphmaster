// TestWalkRandomTrees compares the walker with git on generated trees with
// random .gitignore files and a random tracked subset.
func TestWalkRandomTrees(t *testing.T) {
	if testing.Short() {
		t.Skip("builds several repositories")
	}
	pool := []string{
		"*.log", "!keep.log", "b/", "/a", "c*", "!c1", "**/d/**", "!**/d/x.go",
		"*.go", "!*.go", "e/*.txt", "f", "a/**/z", "[ab]?", "!b/", "*/", "!*/", "**/q",
	}
	names := []string{"a", "b", "c1", "c2", "d", "e", "x.go", "y.txt", "z", "keep.log", "q"}
	rng := rand.New(rand.NewPCG(7, 11))
	for round := range 8 {
		t.Run(fmt.Sprintf("tree%d", round), func(t *testing.T) {
			dir := newRepo(t)
			files := map[string]string{}
			var gen func(prefix string, depth int)
			gen = func(prefix string, depth int) {
				for _, n := range names {
					switch r := rng.IntN(10); {
					case r < 3:
						files[prefix+n+".go"] = "package p\n"
					case r < 5 && depth < 3:
						gen(prefix+n+"/", depth+1)
					case r < 6:
						var lines []string
						for range 1 + rng.IntN(4) {
							lines = append(lines, pool[rng.IntN(len(pool))])
						}
						files[prefix+".gitignore"] = strings.Join(lines, "\n") + "\n"
					}
				}
			}
			gen("", 0)
			writeFiles(t, dir, files)
			var tracked []string
			for p := range files {
				if rng.IntN(3) == 0 {
					tracked = append(tracked, p)
				}
			}
			sort.Strings(tracked)
			if len(tracked) > 0 {
				git(t, dir, append([]string{"add", "-f", "--"}, tracked...)...)
			}
			env := newWalkEnv(t, dir, []string{"z/"})
			res := env.walk(t, nil)
			assertWalkMatchesGit(t, dir, res, "z/")
			t.Logf("files=%d tracked=%d untracked=%d", len(files), len(tracked), len(res.Untracked))
		})
	}
}
