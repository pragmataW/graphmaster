func TestDirRowsRoundTrip(t *testing.T) {
	names := []dirName{{"a.go", kindFile}, {"sub", kindDir}, {"l", kindSymlink}, {"ü x", kindFile}}
	got, err := decodeDirNames(encodeDirNames(names))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != len(names) {
		t.Fatalf("got %v", got)
	}
	for i := range names {
		if got[i] != names[i] {
			t.Fatalf("entry %d: %v != %v", i, got[i], names[i])
		}
	}
	for _, bad := range []string{"x", "\x00", "zname\x00"} {
		if _, err := decodeDirNames([]byte(bad)); err == nil {
			t.Fatalf("decode %q should fail", bad)
		}
	}
	if _, err := DirCacheFromRows([]DirRow{{Path: "x", Names: []byte("q\x00")}}); err == nil {
		t.Fatal("bad row must fail")
	}
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

