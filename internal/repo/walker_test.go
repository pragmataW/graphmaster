// gitOthers returns `git ls-files -o --exclude-standard` split into files
// and nested-repository directories (printed with a trailing slash).
func gitOthers(t *testing.T, dir string, extraExcludes ...string) (files, nested []string) {
	t.Helper()
	args := []string{"ls-files", "-o", "--exclude-standard", "-z"}
	for _, e := range extraExcludes {
		args = append(args, "--exclude="+e)
	}
	for _, p := range splitZ(git(t, dir, args...)) {
		if strings.HasSuffix(p, "/") {
			nested = append(nested, strings.TrimSuffix(p, "/"))
		} else {
			files = append(files, p)
		}
	}
	return files, nested
}

type walkEnv struct {
	root    *Root
	ignore  *Ignore
	tracked *TrackedSet
}

func newWalkEnv(t *testing.T, dir string, excludes []string) walkEnv {
	t.Helper()
	r, err := FindRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	cfg := LoadGitConfig(r)
	ig, err := NewIgnore(r, cfg, excludes)
	if err != nil {
		t.Fatal(err)
	}
	ix, err := ReadIndex(context.Background(), r)
	if err != nil {
		t.Fatal(err)
	}
	return walkEnv{root: r, ignore: ig, tracked: NewTrackedSet(ix.Entries, cfg.IgnoreCase)}
}

func (e walkEnv) walk(t *testing.T, cache *DirCache) *WalkResult {
	t.Helper()
	res, err := Walk(context.Background(), WalkOptions{
		Root: e.root, Tracked: e.tracked, Ignore: e.ignore, Cache: cache,
	})
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func untrackedPaths(res *WalkResult) []string {
	out := make([]string, 0, len(res.Untracked))
	for _, f := range res.Untracked {
		out = append(out, f.Path)
	}
	return out
}

func assertWalkMatchesGit(t *testing.T, dir string, res *WalkResult, excludes ...string) {
	t.Helper()
	wantFiles, wantNested := gitOthers(t, dir, excludes...)
	if d := diffSets(wantFiles, untrackedPaths(res)); d != "" {
		t.Fatalf("untracked files differ from git ls-files -o:\n%s", d)
	}
	if d := diffSets(wantNested, res.NestedRepos); d != "" {
		t.Fatalf("nested repos differ from git:\n%s", d)
	}
	if !sort.SliceIsSorted(res.Untracked, func(i, j int) bool { return res.Untracked[i].Path < res.Untracked[j].Path }) {
		t.Fatal("result not sorted")
	}
}

// buildComplexRepo creates a repository exercising nested .gitignore files,
// negation, info/exclude, core.excludesFile, tracked files under ignored
// directories, a tracked submodule, an untracked nested repository,
// symlinks and content that the filters classify.
func buildComplexRepo(t *testing.T) string {
	t.Helper()
	sub := newRepo(t)
	writeFiles(t, sub, map[string]string{"s.go": "package s\n"})
	git(t, sub, "add", ".")
	git(t, sub, "commit", "-qm", "sub")

	dir := newRepo(t)
	writeFiles(t, dir, map[string]string{
		".gitignore":                "*.log\n!important.log\n/build/\nnode_modules/\ntmp*\n**/cache/**\n!**/cache/keep.txt\n# comment\n",
		"src/.gitignore":            "!debug.log\n*.gen.go\n/local/\n",
		"src/deep/.gitignore":       "*\n!*/\n!*.go\n",
		"docs/.gitignore":           "*.md\n!README.md\n",
		"main.go":                   "package main\n",
		"README.md":                 "# r\n",
		"app.log":                   "x",
		"important.log":             "x",
		"src/a.go":                  "package src\n",
		"src/debug.log":             "x",
		"src/x.gen.go":              "package src\n",
		"src/local/only.go":         "package local\n",
		"src/nested/local/kept.go":  "package local\n",
		"src/deep/keep.go":          "package deep\n",
		"src/deep/drop.txt":         "x",
		"src/deep/more/also.go":     "package more\n",
		"src/deep/more/no.py":       "x = 1\n",
		"build/out.bin":             "x",
		"build/tracked.go":          "package build\n",
		"node_modules/pkg/index.js": "module.exports = 1\n",
		"lib/node_modules/x/y.js":   "1\n",
		"tmpfile":                   "x",
		"tmpdir/inner.go":           "package tmpdir\n",
		"a/cache/x.txt":             "x",
		"a/cache/keep.txt":          "x",
		"docs/guide.md":             "x",
		"docs/README.md":            "x",
		"docs/api/ref.md":           "x",
		"secret.env":                "X=1\n",
		"global.bak":                "x",
		"vendor/dep/dep.go":         "package dep\n",
		"web/app.min.js":            strings.Repeat("var a=1;", 2000),
		"gen/pb.go":                 "// Code generated by protoc. DO NOT EDIT.\npackage gen\n",
		"bin/blob.dat":              "\x00\x01\x02",
		"with space/x y.go":         "package x\n",
		"ünï/файл.go":               "package u\n",
		"nested/.keep":              "",
		"tracked/dir/t.go":          "package dir\n",
		"tracked/dir/untracked.go":  "package dir\n",
		"emptyish/.gitignore":       "",
		"Mixed/CASE.go":             "package mixed\n",
	})
	// Tracked file inside an ignored directory and a tracked dir.
	git(t, dir, "add", "-f", "build/tracked.go")
	git(t, dir, "add", "main.go", ".gitignore", "tracked/dir/t.go", "Mixed/CASE.go")
	git(t, dir, "submodule", "add", "-q", sub, "ext/sub")
	writeFiles(t, dir, map[string]string{"ext/sub/untracked-in-sub.go": "package s\n"})
	git(t, dir, "commit", "-qm", "init")

	// Untracked nested repository.
	git(t, dir, "init", "-q", "nested/inner")
	writeFiles(t, dir, map[string]string{"nested/inner/x.go": "package inner\n"})

	// info/exclude and core.excludesFile.
	writeFiles(t, dir, map[string]string{".git/info/exclude": "*.env\n"})
	gi := filepath.Join(os.Getenv("HOME"), "global-ignore-"+filepath.Base(dir))
	if err := os.WriteFile(gi, []byte("*.bak\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	git(t, dir, "config", "core.excludesFile", gi)

	// Symlinks: to a file, to a directory (listed as a file, not followed),
	// and a symlinked .gitignore (ignored by git).
	for link, target := range map[string]string{
		"link.go":        "main.go",
		"linkdir":        "src",
		"lnk/.gitignore": "../.gitignore",
	} {
		full := filepath.Join(dir, link)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(target, full); err != nil {
			t.Fatal(err)
		}
	}
	writeFiles(t, dir, map[string]string{"lnk/x.log": "x"})
	if err := os.MkdirAll(filepath.Join(dir, "empty", "dirs", "only"), 0o755); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestWalkMatchesGitComplex(t *testing.T) {
	dir := buildComplexRepo(t)
	for _, icase := range []string{"true", "false"} {
		t.Run("ignorecase="+icase, func(t *testing.T) {
			git(t, dir, "config", "core.ignorecase", icase)
			env := newWalkEnv(t, dir, nil)
			res := env.walk(t, nil)
			assertWalkMatchesGit(t, dir, res)
			if len(res.NestedRepos) != 1 || res.NestedRepos[0] != "nested/inner" {
				t.Fatalf("nested repos = %v", res.NestedRepos)
			}
			var sawLink bool
			for _, f := range res.Untracked {
				if f.Path == "linkdir" {
					sawLink = f.Symlink
				}
			}
			if !sawLink {
				t.Fatal("directory symlink must be reported as an untracked symlink")
			}
		})
	}
}

