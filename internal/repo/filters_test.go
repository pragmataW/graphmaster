func TestIsBinary(t *testing.T) {
	if IsBinary([]byte("package main\n")) {
		t.Fatal("text detected as binary")
	}
	if !IsBinary([]byte("abc\x00def")) {
		t.Fatal("NUL not detected")
	}
	late := strings.Repeat("a", BinarySniffLen) + "\x00"
	if IsBinary([]byte(late)) {
		t.Fatal("NUL after the sniff window must be ignored")
	}
}

func TestIsMinified(t *testing.T) {
	normal := strings.Repeat("var x = 1;\n", 500)
	if IsMinified([]byte(normal)) {
		t.Fatal("normal code detected as minified")
	}
	longAvg := strings.Repeat(strings.Repeat("a", 400)+"\n", 10)
	if !IsMinified([]byte(longAvg)) {
		t.Fatal("average line > 300 not detected")
	}
	oneHuge := strings.Repeat("x\n", 2000) + strings.Repeat("b", 10_001) + "\n"
	if !IsMinified([]byte(oneHuge)) {
		t.Fatal("single line > 10k not detected")
	}
	short := strings.Repeat("a", 350) // one short-ish line in a tiny file
	if IsMinified([]byte(short)) {
		t.Fatal("tiny single-line file must not count as minified")
	}
}

func TestIsGenerated(t *testing.T) {
	yes := []string{
		"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n",
		"// Copyright 2024\n// License\n\n// Code generated by stringer; DO NOT EDIT.\n\npackage y\n",
		"/**\n * @generated\n */\nclass A {}\n",
		"# This file is auto-generated, do not modify\nx = 1\n",
		"// <auto-generated>\n// </auto-generated>\nclass C {}\n",
		"# Code generated by tool. DO NOT EDIT.\nx = 1\n",
		"/* Code generated by tool. DO NOT EDIT. */\nint x;\n",
		"-- Code generated by sqlc. DO NOT EDIT.\n",
		"<!-- Code generated by tool. DO NOT EDIT. -->\n",
	}
	for _, s := range yes {
		if !IsGenerated([]byte(s)) {
			t.Errorf("not detected as generated: %q", s)
		}
	}
	no := []string{
		"package x\n\nfunc Code() {}\n",
		"package x\n" + strings.Repeat("\n", 20) + "// the auto-generated id is returned\n",
		"// Code generated by hand, feel free to edit\n",
		// Generator sources that merely print the marker are not generated.
		"package gen\n\nvar lines = []string{\n\t\"// Code generated by gen. DO NOT EDIT.\",\n}\n",
		"package gen\n\nvar hdr = []string{\n\t`// Code generated by gen. DO NOT EDIT.`,\n}\n",
		"package gen\n\nfunc w() { fmt.Fprintln(w, \"Code generated by gen. DO NOT EDIT.\") }\n",
	}
	for _, s := range no {
		if IsGenerated([]byte(s)) {
			t.Errorf("false positive: %q", s)
		}
	}
}

func TestClassify(t *testing.T) {
	const maxSize = 1 << 20
	cases := []struct {
		name    string
		path    string
		size    int64
		content string
		want    model.FileStatus
	}{
		{"ok", "a.go", 13, "package main\n", model.StatusOK},
		{"unsupported", "README.md", 4, "# hi", model.StatusUnsupported},
		{"too big", "a.go", maxSize + 1, "", model.StatusTooBig},
		{"binary", "a.c", 3, "a\x00b", model.StatusBinary},
		{"generated", "a.go", 50, "// Code generated by x. DO NOT EDIT.\npackage a\n", model.StatusGenerated},
		{"minified", "a.js", 0, strings.Repeat(strings.Repeat("v", 500)+";\n", 4), model.StatusMinified},
	}
	for _, c := range cases {
		size := c.size
		if size == 0 {
			size = int64(len(c.content))
		}
		got := Classify(c.path, size, []byte(c.content), maxSize)
		if got != c.want {
			t.Errorf("%s: Classify = %v, want %v", c.name, got, c.want)
		}
	}
}

func TestDetectLang(t *testing.T) {
	cases := []struct {
		path string
		head string
		want model.Lang
	}{
		{"src/main.go", "", model.LangGo},
		{"x/y.tsx", "", model.LangTSX},
		{"lib/a.hpp", "", model.LangCPP},
		{"bin/tool", "#!/usr/bin/env python3\nprint(1)\n", model.LangPython},
		{"bin/run", "#!/usr/bin/env node\n", model.LangJavaScript},
		{"bin/sh", "#!/bin/sh\n", model.LangUnknown},
		{"Makefile", "all:\n", model.LangUnknown},
		{"notes.txt", "#!/usr/bin/python\n", model.LangUnknown}, // extension wins
	}
	for _, c := range cases {
		if got := DetectLang(c.path, []byte(c.head)); got != c.want {
			t.Errorf("DetectLang(%q) = %v, want %v", c.path, got, c.want)
		}
	}
}
